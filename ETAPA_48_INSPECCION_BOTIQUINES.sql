create table if not exists public.botiquin_componentes_base (
  id uuid primary key default gen_random_uuid(),
  tipo text not null check (tipo in ('UBICACION','VEHICULO')),
  orden integer not null,
  nombre text not null,
  cantidad integer not null default 1 check (cantidad >= 0),
  activo boolean not null default true,
  unique(tipo,orden)
);

create table if not exists public.botiquin_configuraciones (
  id uuid primary key default gen_random_uuid(),
  proyecto_id uuid not null references public.proyectos(id) on delete cascade,
  tipo text not null check (tipo in ('UBICACION','VEHICULO')),
  placa_vehiculo text,
  activo boolean not null default true,
  creado_por uuid references public.perfiles(id) on delete set null,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create unique index if not exists uq_botiquin_config_scope
on public.botiquin_configuraciones (
  proyecto_id,
  tipo,
  coalesce(upper(btrim(placa_vehiculo)),'')
);

create table if not exists public.botiquin_config_componentes (
  id uuid primary key default gen_random_uuid(),
  configuracion_id uuid not null references public.botiquin_configuraciones(id) on delete cascade,
  orden integer not null,
  nombre text not null,
  cantidad integer not null default 1 check (cantidad >= 0),
  activo boolean not null default true,
  unique(configuracion_id,orden)
);

create table if not exists public.inspecciones_botiquin (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  proyecto_id uuid not null references public.proyectos(id),
  tipo text not null check (tipo in ('UBICACION','VEHICULO')),
  lugar_id uuid references public.lugares_proyecto(id) on delete set null,
  area_proyecto_id uuid references public.areas_proyecto(id) on delete set null,
  ubicacion_nombre text,
  codigo_botiquin text,
  placa_vehiculo text,
  responsable_botiquin text,
  fecha_inspeccion date not null,
  inspector_id uuid references public.perfiles(id) on delete set null,
  inspector_nombre text not null,
  inspector_cargo text,
  firma_ruta text,
  foto_botiquin_ruta text,
  foto_botiquin_descripcion text,
  estado text not null default 'CONFORME'
    check (estado in ('CONFORME','OBSERVADO','OCURRENCIA_GENERADA')),
  responsable_correccion_id uuid references public.responsables_correccion(id) on delete set null,
  area_responsable_proyecto_id uuid references public.areas_proyecto(id) on delete set null,
  accion_requerida text,
  potencial_perdida_id uuid references public.potenciales_perdida(id) on delete set null,
  fecha_limite date,
  creado_por uuid references public.perfiles(id) on delete set null,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.inspeccion_botiquin_items (
  id uuid primary key default gen_random_uuid(),
  inspeccion_id uuid not null references public.inspecciones_botiquin(id) on delete cascade,
  orden integer not null,
  componente text not null,
  cantidad_requerida integer not null default 1 check (cantidad_requerida >= 0),
  resultado text not null check (resultado in ('SI','NO')),
  observacion text,
  foto_ruta text,
  creado_en timestamptz not null default now(),
  unique(inspeccion_id,orden)
);

alter table public.ocurrencias
  add column if not exists botiquin_inspeccion_id uuid references public.inspecciones_botiquin(id) on delete set null;

create unique index if not exists uq_ocurrencia_botiquin_inspeccion
on public.ocurrencias(botiquin_inspeccion_id)
where botiquin_inspeccion_id is not null;

