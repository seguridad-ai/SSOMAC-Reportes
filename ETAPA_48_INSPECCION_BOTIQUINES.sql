create or replace function public.puede_configurar_botiquin(p_proyecto_id uuid)
returns boolean
language sql
security definer
stable
set search_path=public,pg_temp
as $$
  select
    public.puede_gestionar_proyecto(p_proyecto_id)
    and coalesce(public.rol_actual() in ('ADMIN','PROYECTO','ING_SEGURIDAD'),false);
$$;

revoke all on function public.puede_configurar_botiquin(uuid) from public;
grant execute on function public.puede_configurar_botiquin(uuid) to authenticated;

create or replace function public.obtener_componentes_botiquin_efectivos(
  p_proyecto_id uuid,
  p_tipo text,
  p_placa_vehiculo text default null
)
returns table(
  origen text,
  configuracion_id uuid,
  orden integer,
  nombre text,
  cantidad integer
)
language plpgsql
security definer
stable
set search_path=public,pg_temp
as $$
declare
  v_config uuid;
  v_tipo text := upper(btrim(coalesce(p_tipo,'')));
  v_placa text := nullif(upper(btrim(coalesce(p_placa_vehiculo,''))), '');
begin
  if not public.puede_acceder_proyecto(p_proyecto_id) then
    raise exception 'No tiene acceso al proyecto seleccionado';
  end if;
  if v_tipo not in ('UBICACION','VEHICULO') then
    raise exception 'Tipo de botiquín inválido';
  end if;

  if v_tipo='VEHICULO' and v_placa is not null then
    select c.id into v_config
    from public.botiquin_configuraciones c
    where c.proyecto_id=p_proyecto_id and c.tipo=v_tipo and c.activo=true
      and upper(btrim(coalesce(c.placa_vehiculo,'')))=v_placa
    limit 1;
  end if;

  if v_config is null then
    select c.id into v_config
    from public.botiquin_configuraciones c
    where c.proyecto_id=p_proyecto_id and c.tipo=v_tipo and c.activo=true
      and nullif(btrim(coalesce(c.placa_vehiculo,'')),'') is null
    limit 1;
  end if;

  if v_config is not null then
    return query
    select 'PERSONALIZADA'::text,v_config,cc.orden,cc.nombre,cc.cantidad
    from public.botiquin_config_componentes cc
    where cc.configuracion_id=v_config and cc.activo=true
    order by cc.orden;
  else
    return query
    select 'CORPORATIVA'::text,null::uuid,b.orden,b.nombre,b.cantidad
    from public.botiquin_componentes_base b
    where b.tipo=v_tipo and b.activo=true
    order by b.orden;
  end if;
end;
$$;

revoke all on function public.obtener_componentes_botiquin_efectivos(uuid,text,text) from public;
grant execute on function public.obtener_componentes_botiquin_efectivos(uuid,text,text) to authenticated;

create or replace function public.guardar_configuracion_botiquin(
  p_proyecto_id uuid,
  p_tipo text,
  p_placa_vehiculo text,
  p_componentes jsonb
)
returns uuid
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_config uuid;
  v_tipo text := upper(btrim(coalesce(p_tipo,'')));
  v_placa text := nullif(upper(btrim(coalesce(p_placa_vehiculo,''))), '');
  v_item jsonb;
  v_orden integer := 0;
begin
  if not public.puede_configurar_botiquin(p_proyecto_id) then
    raise exception 'No tiene permisos para configurar componentes en este proyecto';
  end if;
  if v_tipo not in ('UBICACION','VEHICULO') then
    raise exception 'Tipo de botiquín inválido';
  end if;
  if v_tipo='UBICACION' then v_placa:=null; end if;
  if jsonb_typeof(p_componentes) <> 'array' or jsonb_array_length(p_componentes)=0 then
    raise exception 'Debe conservar al menos un componente';
  end if;

  select id into v_config
  from public.botiquin_configuraciones
  where proyecto_id=p_proyecto_id and tipo=v_tipo
    and coalesce(upper(btrim(placa_vehiculo)),'')=coalesce(v_placa,'')
  limit 1;

  if v_config is null then
    insert into public.botiquin_configuraciones(proyecto_id,tipo,placa_vehiculo,creado_por)
    values(p_proyecto_id,v_tipo,v_placa,auth.uid())
    returning id into v_config;
  else
    update public.botiquin_configuraciones
    set activo=true,placa_vehiculo=v_placa,actualizado_en=now()
    where id=v_config;
  end if;

  delete from public.botiquin_config_componentes where configuracion_id=v_config;

  for v_item in select * from jsonb_array_elements(p_componentes)
  loop
    if btrim(coalesce(v_item->>'nombre','')) <> '' then
      v_orden:=v_orden+1;
      insert into public.botiquin_config_componentes(configuracion_id,orden,nombre,cantidad,activo)
      values(v_config,v_orden,btrim(v_item->>'nombre'),greatest(coalesce((v_item->>'cantidad')::integer,1),0),true);
    end if;
  end loop;

  if v_orden=0 then raise exception 'Debe conservar al menos un componente válido'; end if;
  return v_config;
end;
$$;

revoke all on function public.guardar_configuracion_botiquin(uuid,text,text,jsonb) from public;
grant execute on function public.guardar_configuracion_botiquin(uuid,text,text,jsonb) to authenticated;

create or replace function public.restaurar_configuracion_botiquin(
  p_proyecto_id uuid,
  p_tipo text,
  p_placa_vehiculo text default null
)
returns boolean
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_tipo text := upper(btrim(coalesce(p_tipo,'')));
  v_placa text := nullif(upper(btrim(coalesce(p_placa_vehiculo,''))), '');
begin
  if not public.puede_configurar_botiquin(p_proyecto_id) then
    raise exception 'No tiene permisos para restaurar esta configuración';
  end if;
  if v_tipo='UBICACION' then v_placa:=null; end if;
  delete from public.botiquin_configuraciones
  where proyecto_id=p_proyecto_id and tipo=v_tipo
    and coalesce(upper(btrim(placa_vehiculo)),'')=coalesce(v_placa,'');
  return true;
end;
$$;

revoke all on function public.restaurar_configuracion_botiquin(uuid,text,text) from public;
grant execute on function public.restaurar_configuracion_botiquin(uuid,text,text) to authenticated;

