-- ============================================================
-- ETAPA 44 - ELIMINACION CONTROLADA DE OCURRENCIAS Y REPORTES
-- SSOMAC Digital - Explo Drilling Peru
-- Requiere ETAPA 43 aplicada previamente.
-- Solo el rol ADMIN puede ejecutar las eliminaciones.
-- ============================================================

begin;

-- ------------------------------------------------------------
-- 1. AUDITORIA PERMANENTE DE ELIMINACIONES
-- ------------------------------------------------------------
create table if not exists public.auditoria_eliminaciones (
  id bigint generated by default as identity primary key,
  tipo_registro text not null,
  registro_id uuid,
  codigo_registro text not null,
  proyecto_id uuid,
  proyecto_nombre text,
  motivo text not null,
  eliminado_por_id uuid,
  eliminado_por_nombre text,
  eliminado_en timestamptz not null default now(),
  detalle jsonb not null default '{}'::jsonb
);

alter table public.auditoria_eliminaciones enable row level security;

revoke insert, update, delete on public.auditoria_eliminaciones from anon, authenticated;
grant select on public.auditoria_eliminaciones to authenticated;

drop policy if exists "v44 solo admin lee auditoria" on public.auditoria_eliminaciones;
create policy "v44 solo admin lee auditoria"
on public.auditoria_eliminaciones
as restrictive
for select
to authenticated
using (public.es_admin_sistema());

-- ------------------------------------------------------------
-- 2. PREVISUALIZACION DE OCURRENCIA
-- ------------------------------------------------------------
drop function if exists public.admin_previsualizar_eliminacion_ocurrencia(uuid);
create or replace function public.admin_previsualizar_eliminacion_ocurrencia(
  p_ocurrencia_id uuid
)
returns table(
  codigo text,
  proyecto text,
  reporte_vinculado_id uuid,
  reporte_vinculado_codigo text,
  cantidad_evidencias bigint
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
begin
  if not public.es_admin_sistema() then
    raise exception 'Solo el ADMIN puede eliminar registros.';
  end if;

  return query
  select
    'OC-'||lpad(o.numero::text,6,'0'),
    coalesce(p.nombre,'SIN PROYECTO'),
    r.id,
    case when r.numero is null then null else 'REP-'||lpad(r.numero::text,6,'0') end,
    (select count(*) from public.evidencias e where e.ocurrencia_id=o.id)
  from public.ocurrencias o
  left join public.proyectos p on p.id=o.proyecto_id
  left join lateral (
    select rt.id,rt.numero
    from public.reportes_trabajadores rt
    where rt.ocurrencia_id=o.id
    order by rt.creado_en asc nulls last
    limit 1
  ) r on true
  where o.id=p_ocurrencia_id;

  if not found then raise exception 'La ocurrencia no existe o ya fue eliminada.'; end if;
end;
$$;

revoke all on function public.admin_previsualizar_eliminacion_ocurrencia(uuid) from public;
grant execute on function public.admin_previsualizar_eliminacion_ocurrencia(uuid) to authenticated;

-- ------------------------------------------------------------
-- 3. PREVISUALIZACION DE REPORTE DE TRABAJADOR
-- ------------------------------------------------------------
drop function if exists public.admin_previsualizar_eliminacion_reporte(uuid);
create or replace function public.admin_previsualizar_eliminacion_reporte(
  p_reporte_id uuid
)
returns table(
  codigo text,
  proyecto text,
  ocurrencia_vinculada_id uuid,
  ocurrencia_vinculada_codigo text
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
begin
  if not public.es_admin_sistema() then
    raise exception 'Solo el ADMIN puede eliminar registros.';
  end if;

  return query
  select
    'REP-'||lpad(r.numero::text,6,'0'),
    coalesce(p.nombre,'SIN PROYECTO'),
    o.id,
    case when o.numero is null then null else 'OC-'||lpad(o.numero::text,6,'0') end
  from public.reportes_trabajadores r
  left join public.proyectos p on p.id=r.proyecto_id
  left join public.ocurrencias o on o.id=r.ocurrencia_id
  where r.id=p_reporte_id;

  if not found then raise exception 'El reporte no existe o ya fue eliminado.'; end if;
end;
$$;

revoke all on function public.admin_previsualizar_eliminacion_reporte(uuid) from public;
grant execute on function public.admin_previsualizar_eliminacion_reporte(uuid) to authenticated;

-- ------------------------------------------------------------
-- 4. ELIMINAR OCURRENCIA Y TODOS SUS REGISTROS OPERATIVOS
-- ------------------------------------------------------------
drop function if exists public.admin_eliminar_ocurrencia(uuid,text,text,boolean);
create or replace function public.admin_eliminar_ocurrencia(
  p_ocurrencia_id uuid,
  p_motivo text,
  p_confirmacion text,
  p_eliminar_reporte_vinculado boolean default false
)
returns table(
  ok boolean,
  codigo text,
  proyecto text,
  rutas_storage text[],
  elimino_reporte_vinculado boolean
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_occ record;
  v_rep record;
  v_actor text;
  v_paths text[] := array[]::text[];
begin
  if not public.es_admin_sistema() then
    raise exception 'Solo el ADMIN puede eliminar registros.';
  end if;
  if upper(btrim(coalesce(p_confirmacion,'')))<>'ELIMINAR' then
    raise exception 'Debes escribir ELIMINAR para confirmar.';
  end if;
  if length(btrim(coalesce(p_motivo,'')))<5 then
    raise exception 'Registra un motivo de eliminación de al menos 5 caracteres.';
  end if;

  select o.*,p.nombre as proyecto_nombre
  into v_occ
  from public.ocurrencias o
  left join public.proyectos p on p.id=o.proyecto_id
  where o.id=p_ocurrencia_id;
  if not found then raise exception 'La ocurrencia no existe o ya fue eliminada.'; end if;

  select rt.* into v_rep
  from public.reportes_trabajadores rt
  where rt.ocurrencia_id=p_ocurrencia_id
  order by rt.creado_en asc nulls last
  limit 1;

  if v_rep.id is not null and not p_eliminar_reporte_vinculado then
    raise exception 'Esta ocurrencia está vinculada al reporte REP-%. Confirma la eliminación de ambos registros.',lpad(v_rep.numero::text,6,'0');
  end if;

  select coalesce(array_agg(distinct e.ruta_archivo) filter(where e.ruta_archivo is not null and btrim(e.ruta_archivo)<>''),array[]::text[])
  into v_paths
  from public.evidencias e
  where e.ocurrencia_id=p_ocurrencia_id;

  if v_rep.id is not null and p_eliminar_reporte_vinculado and v_rep.ruta_foto is not null and btrim(v_rep.ruta_foto)<>'' then
    v_paths:=array_append(v_paths,v_rep.ruta_foto);
  end if;

  select nullif(btrim(concat_ws(' ',p.nombres,p.apellidos)),'') into v_actor
  from public.perfiles p where p.id=auth.uid();
  v_actor:=coalesce(v_actor,'ADMIN');

  insert into public.auditoria_eliminaciones(
    tipo_registro,registro_id,codigo_registro,proyecto_id,proyecto_nombre,
    motivo,eliminado_por_id,eliminado_por_nombre,detalle
  ) values(
    case when v_rep.id is not null and p_eliminar_reporte_vinculado then 'OCURRENCIA_Y_REPORTE' else 'OCURRENCIA' end,
    v_occ.id,
    'OC-'||lpad(v_occ.numero::text,6,'0'),
    v_occ.proyecto_id,
    v_occ.proyecto_nombre,
    btrim(p_motivo),
    auth.uid(),
    v_actor,
    jsonb_build_object(
      'ocurrencia',to_jsonb(v_occ),
      'reporte_vinculado',case when v_rep.id is null then null else to_jsonb(v_rep) end,
      'rutas_storage',to_jsonb(v_paths)
    )
  );

  -- El reporte enlazado debe borrarse antes que la ocurrencia para evitar FK huérfana.
  if v_rep.id is not null and p_eliminar_reporte_vinculado then
    delete from public.reportes_trabajadores where ocurrencia_id=p_ocurrencia_id;
  end if;

  -- Dependencias conocidas del modelo SSOMAC Digital.
  delete from public.ocurrencia_causas_inmediatas where ocurrencia_id=p_ocurrencia_id;
  delete from public.ocurrencia_causas_basicas where ocurrencia_id=p_ocurrencia_id;
  delete from public.evidencias where ocurrencia_id=p_ocurrencia_id;
  delete from public.asignaciones_levantamiento where ocurrencia_id=p_ocurrencia_id;
  delete from public.ampliaciones_plazo where ocurrencia_id=p_ocurrencia_id;
  delete from public.historial_ocurrencias where ocurrencia_id=p_ocurrencia_id;
  delete from public.ocurrencias where id=p_ocurrencia_id;

  if not found then raise exception 'No se pudo eliminar la ocurrencia.'; end if;

  return query select
    true,
    'OC-'||lpad(v_occ.numero::text,6,'0'),
    coalesce(v_occ.proyecto_nombre,'SIN PROYECTO'),
    v_paths,
    (v_rep.id is not null and p_eliminar_reporte_vinculado);
end;
$$;

revoke all on function public.admin_eliminar_ocurrencia(uuid,text,text,boolean) from public;
grant execute on function public.admin_eliminar_ocurrencia(uuid,text,text,boolean) to authenticated;

-- ------------------------------------------------------------
-- 5. ELIMINAR REPORTE DE TRABAJADOR
-- Si ya generó una ocurrencia, la eliminación debe ser conjunta.
-- ------------------------------------------------------------
drop function if exists public.admin_eliminar_reporte(uuid,text,text,boolean);
create or replace function public.admin_eliminar_reporte(
  p_reporte_id uuid,
  p_motivo text,
  p_confirmacion text,
  p_eliminar_ocurrencia_vinculada boolean default false
)
returns table(
  ok boolean,
  codigo text,
  proyecto text,
  rutas_storage text[],
  elimino_ocurrencia_vinculada boolean
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_rep record;
  v_actor text;
  v_paths text[] := array[]::text[];
  v_occ_result record;
begin
  if not public.es_admin_sistema() then
    raise exception 'Solo el ADMIN puede eliminar registros.';
  end if;
  if upper(btrim(coalesce(p_confirmacion,'')))<>'ELIMINAR' then
    raise exception 'Debes escribir ELIMINAR para confirmar.';
  end if;
  if length(btrim(coalesce(p_motivo,'')))<5 then
    raise exception 'Registra un motivo de eliminación de al menos 5 caracteres.';
  end if;

  select r.*,p.nombre as proyecto_nombre
  into v_rep
  from public.reportes_trabajadores r
  left join public.proyectos p on p.id=r.proyecto_id
  where r.id=p_reporte_id;
  if not found then raise exception 'El reporte no existe o ya fue eliminado.'; end if;

  if v_rep.ocurrencia_id is not null then
    if not p_eliminar_ocurrencia_vinculada then
      raise exception 'Este reporte ya generó una ocurrencia formal. Confirma la eliminación de ambos registros.';
    end if;
    select * into v_occ_result
    from public.admin_eliminar_ocurrencia(v_rep.ocurrencia_id,p_motivo,p_confirmacion,true);
    return query select
      true,
      'REP-'||lpad(v_rep.numero::text,6,'0'),
      coalesce(v_rep.proyecto_nombre,'SIN PROYECTO'),
      v_occ_result.rutas_storage,
      true;
    return;
  end if;

  if v_rep.ruta_foto is not null and btrim(v_rep.ruta_foto)<>'' then
    v_paths:=array_append(v_paths,v_rep.ruta_foto);
  end if;

  select nullif(btrim(concat_ws(' ',p.nombres,p.apellidos)),'') into v_actor
  from public.perfiles p where p.id=auth.uid();
  v_actor:=coalesce(v_actor,'ADMIN');

  insert into public.auditoria_eliminaciones(
    tipo_registro,registro_id,codigo_registro,proyecto_id,proyecto_nombre,
    motivo,eliminado_por_id,eliminado_por_nombre,detalle
  ) values(
    'REPORTE_TRABAJADOR',
    v_rep.id,
    'REP-'||lpad(v_rep.numero::text,6,'0'),
    v_rep.proyecto_id,
    v_rep.proyecto_nombre,
    btrim(p_motivo),
    auth.uid(),
    v_actor,
    jsonb_build_object('reporte',to_jsonb(v_rep),'rutas_storage',to_jsonb(v_paths))
  );

  delete from public.reportes_trabajadores where id=p_reporte_id;
  if not found then raise exception 'No se pudo eliminar el reporte.'; end if;

  return query select
    true,
    'REP-'||lpad(v_rep.numero::text,6,'0'),
    coalesce(v_rep.proyecto_nombre,'SIN PROYECTO'),
    v_paths,
    false;
end;
$$;

revoke all on function public.admin_eliminar_reporte(uuid,text,text,boolean) from public;
grant execute on function public.admin_eliminar_reporte(uuid,text,text,boolean) to authenticated;

-- ------------------------------------------------------------
-- 6. BLOQUEAR DELETE DIRECTO DESDE EL FRONTEND
-- El borrado se hace únicamente por los RPC anteriores.
-- ------------------------------------------------------------
revoke delete on public.ocurrencias from anon,authenticated;
revoke delete on public.reportes_trabajadores from anon,authenticated;
revoke delete on public.evidencias from anon,authenticated;

-- ------------------------------------------------------------
-- 7. STORAGE: SOLO ADMIN PUEDE BORRAR ARCHIVOS DEL BUCKET
-- Se usa una política permisiva + restrictiva para que ninguna política
-- antigua más amplia pueda habilitar DELETE a otros roles.
-- ------------------------------------------------------------
drop policy if exists "v44 admin borrar evidencias storage" on storage.objects;
drop policy if exists "v44 restringir borrado evidencias storage" on storage.objects;

create policy "v44 admin borrar evidencias storage"
on storage.objects
for delete
to authenticated
using (bucket_id='evidencias-ssomac' and public.es_admin_sistema());

create policy "v44 restringir borrado evidencias storage"
on storage.objects
as restrictive
for delete
to authenticated
using (bucket_id<>'evidencias-ssomac' or public.es_admin_sistema());

commit;

