-- ============================================================
-- ETAPA 47 REVISADA
-- INSPECCIONES POR FORMATOS CORPORATIVOS
-- Módulo 1: INSPECCIÓN GENERAL
-- Formato: EDP-SIG-SSOMAC-RE-PA-191-03
--
-- IMPORTANTE:
-- La Inspección General NO genera una ocurrencia.
-- Su seguimiento y corrección permanecen dentro de este módulo.
-- Los formatos específicos (Botiquín, Extintores, etc.) se
-- implementarán posteriormente con su propia lógica y podrán
-- generar ocurrencias cuando corresponda.
-- ============================================================

begin;

create table if not exists public.inspecciones_generales (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  proyecto_id uuid not null references public.proyectos(id),
  inspector_nombre text not null,
  area_inspeccionada text not null,
  fecha_inspeccion date not null,
  tipo_inspeccion text not null
    check (tipo_inspeccion in ('IP','INP','IC')),
  numero_trabajadores integer
    check (numero_trabajadores is null or numero_trabajadores >= 0),
  responsable_registro_nombre text not null,
  responsable_registro_cargo text,
  responsable_registro_fecha date not null default current_date,
  firma_ruta text,
  estado text not null default 'PENDIENTE_CORRECCION'
    check (estado in ('PENDIENTE_CORRECCION','COMPLETADA')),
  creado_por_id uuid not null default auth.uid() references public.perfiles(id),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.inspeccion_general_items (
  id uuid primary key default gen_random_uuid(),
  inspeccion_id uuid not null
    references public.inspecciones_generales(id) on delete cascade,
  item_no smallint not null check (item_no between 1 and 10),
  descripcion text not null,
  causa_acto text,
  causa_condicion text,
  factor_trabajo text,
  factor_personal text,
  observacion_foto_ruta text,
  accion_correctiva text not null,
  correccion_foto_ruta text,
  responsable text not null,
  potencial_riesgo text not null
    check (potencial_riesgo in ('A','B','C')),
  fecha_correccion date,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique(inspeccion_id,item_no)
);

create or replace function public.e47_set_actualizado_en()
returns trigger
language plpgsql
as $$
begin
  new.actualizado_en=now();
  return new;
end;
$$;

drop trigger if exists trg_e47_inspecciones_generales_actualizado
on public.inspecciones_generales;
create trigger trg_e47_inspecciones_generales_actualizado
before update on public.inspecciones_generales
for each row execute function public.e47_set_actualizado_en();

drop trigger if exists trg_e47_inspeccion_items_actualizado
on public.inspeccion_general_items;
create trigger trg_e47_inspeccion_items_actualizado
before update on public.inspeccion_general_items
for each row execute function public.e47_set_actualizado_en();

alter table public.inspecciones_generales enable row level security;
alter table public.inspeccion_general_items enable row level security;

drop policy if exists "e47 inspecciones generales select" on public.inspecciones_generales;
drop policy if exists "e47 inspecciones generales insert" on public.inspecciones_generales;
drop policy if exists "e47 inspecciones generales update" on public.inspecciones_generales;
drop policy if exists "e47 inspecciones generales delete" on public.inspecciones_generales;

create policy "e47 inspecciones generales select"
on public.inspecciones_generales
for select to authenticated
using (public.puede_acceder_proyecto(proyecto_id));

create policy "e47 inspecciones generales insert"
on public.inspecciones_generales
for insert to authenticated
with check (
  public.puede_gestionar_proyecto(proyecto_id)
  and creado_por_id=auth.uid()
);

create policy "e47 inspecciones generales update"
on public.inspecciones_generales
for update to authenticated
using (public.puede_gestionar_proyecto(proyecto_id))
with check (public.puede_gestionar_proyecto(proyecto_id));

create policy "e47 inspecciones generales delete"
on public.inspecciones_generales
for delete to authenticated
using (public.es_admin_sistema());

drop policy if exists "e47 items select" on public.inspeccion_general_items;
drop policy if exists "e47 items insert" on public.inspeccion_general_items;
drop policy if exists "e47 items update" on public.inspeccion_general_items;
drop policy if exists "e47 items delete" on public.inspeccion_general_items;

create policy "e47 items select"
on public.inspeccion_general_items
for select to authenticated
using (
  exists (
    select 1 from public.inspecciones_generales i
    where i.id=inspeccion_id
      and public.puede_acceder_proyecto(i.proyecto_id)
  )
);

create policy "e47 items insert"
on public.inspeccion_general_items
for insert to authenticated
with check (
  exists (
    select 1 from public.inspecciones_generales i
    where i.id=inspeccion_id
      and public.puede_gestionar_proyecto(i.proyecto_id)
  )
);

create policy "e47 items update"
on public.inspeccion_general_items
for update to authenticated
using (
  exists (
    select 1 from public.inspecciones_generales i
    where i.id=inspeccion_id
      and public.puede_gestionar_proyecto(i.proyecto_id)
  )
)
with check (
  exists (
    select 1 from public.inspecciones_generales i
    where i.id=inspeccion_id
      and public.puede_gestionar_proyecto(i.proyecto_id)
  )
);

create policy "e47 items delete"
on public.inspeccion_general_items
for delete to authenticated
using (
  exists (
    select 1 from public.inspecciones_generales i
    where i.id=inspeccion_id
      and public.puede_gestionar_proyecto(i.proyecto_id)
  )
);

grant select,insert,update,delete on public.inspecciones_generales to authenticated;
grant select,insert,update,delete on public.inspeccion_general_items to authenticated;
grant usage,select on sequence public.inspecciones_generales_numero_seq to authenticated;

-- Verificación
select table_name
from information_schema.tables
where table_schema='public'
  and table_name in ('inspecciones_generales','inspeccion_general_items')
order by table_name;

commit;
