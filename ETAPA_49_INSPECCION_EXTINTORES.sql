begin;

create table if not exists public.extintores (
  id uuid primary key default gen_random_uuid(),
  proyecto_id uuid not null references public.proyectos(id) on delete cascade,
  lugar_id uuid references public.lugares_proyecto(id) on delete set null,
  area_proyecto_id uuid references public.areas_proyecto(id) on delete set null,
  codigo_extintor text not null,
  ubicacion_nombre text,
  tipo_extintor text,
  agente_extintor text,
  capacidad text,
  marca_extintor text,
  marca_recarga text,
  fecha_recarga_actual date,
  fecha_recarga_proxima date,
  fecha_hidrostatica_actual date,
  fecha_hidrostatica_proxima date,
  activo boolean not null default true,
  creado_por uuid references public.perfiles(id) on delete set null,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create unique index if not exists uq_extintor_codigo_proyecto
on public.extintores(proyecto_id, upper(btrim(codigo_extintor)));

create table if not exists public.inspecciones_extintores (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  proyecto_id uuid not null references public.proyectos(id),
  fecha_inspeccion date not null,
  inspector_id uuid references public.perfiles(id) on delete set null,
  inspector_nombre text not null,
  vb_residente text,
  estado text not null default 'CONFORME'
    check (estado in ('CONFORME','OBSERVADO')),
  creado_por uuid references public.perfiles(id) on delete set null,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.inspeccion_extintor_detalles (
  id uuid primary key default gen_random_uuid(),
  inspeccion_id uuid not null references public.inspecciones_extintores(id) on delete cascade,
  extintor_id uuid references public.extintores(id) on delete set null,
  orden integer not null,

  codigo_extintor text not null,
  ubicacion_nombre text,
  tipo_extintor text,
  agente_extintor text,
  capacidad text,
  marca_extintor text,
  marca_recarga text,
  fecha_recarga_actual date,
  fecha_recarga_proxima date,
  fecha_hidrostatica_actual date,
  fecha_hidrostatica_proxima date,

  etiqueta_mantenimiento text not null default 'NA' check (etiqueta_mantenimiento in ('OK','MAL','NA')),
  instrucciones_uso text not null default 'NA' check (instrucciones_uso in ('OK','MAL','NA')),
  prueba_hidrostatica text not null default 'NA' check (prueba_hidrostatica in ('OK','MAL','NA')),
  collar_verificacion text not null default 'NA' check (collar_verificacion in ('OK','MAL','NA')),
  tarjeta_inspeccion text not null default 'NA' check (tarjeta_inspeccion in ('OK','MAL','NA')),
  manometro text not null default 'NA' check (manometro in ('OK','MAL','NA')),
  botella text not null default 'NA' check (botella in ('OK','MAL','NA')),
  valvula text not null default 'NA' check (valvula in ('OK','MAL','NA')),
  manguera text not null default 'NA' check (manguera in ('OK','MAL','NA')),
  precinto_seguridad text not null default 'NA' check (precinto_seguridad in ('OK','MAL','NA')),

  resultado text not null default 'CONFORME'
    check (resultado in ('CONFORME','OBSERVADO')),
  observacion text,
  foto_ruta text,
  foto_descripcion text,
  medida_control text,
  responsable_control_id uuid references public.responsables_correccion(id) on delete set null,
  responsable_control_nombre text,
  fecha_verificacion date,
  ocurrencia_id uuid references public.ocurrencias(id) on delete set null,
  creado_en timestamptz not null default now(),
  unique(inspeccion_id, orden)
);

alter table public.ocurrencias
  add column if not exists extintor_detalle_id uuid references public.inspeccion_extintor_detalles(id) on delete set null;

create unique index if not exists uq_ocurrencia_extintor_detalle
on public.ocurrencias(extintor_detalle_id)
where extintor_detalle_id is not null;

-- ------------------------------------------------------------
-- RLS
-- ------------------------------------------------------------
alter table public.extintores enable row level security;
alter table public.inspecciones_extintores enable row level security;
alter table public.inspeccion_extintor_detalles enable row level security;

drop policy if exists "e49 extintores select" on public.extintores;
create policy "e49 extintores select" on public.extintores
for select to authenticated using (public.puede_acceder_proyecto(proyecto_id));

drop policy if exists "e49 extintores insert" on public.extintores;
create policy "e49 extintores insert" on public.extintores
for insert to authenticated with check (public.puede_gestionar_proyecto(proyecto_id));

drop policy if exists "e49 extintores update" on public.extintores;
create policy "e49 extintores update" on public.extintores
for update to authenticated using (public.puede_gestionar_proyecto(proyecto_id)) with check (public.puede_gestionar_proyecto(proyecto_id));

drop policy if exists "e49 extintores delete" on public.extintores;
create policy "e49 extintores delete" on public.extintores
for delete to authenticated using (public.es_admin_sistema());

drop policy if exists "e49 inspecciones select" on public.inspecciones_extintores;
create policy "e49 inspecciones select" on public.inspecciones_extintores
for select to authenticated using (public.puede_acceder_proyecto(proyecto_id));

drop policy if exists "e49 inspecciones insert" on public.inspecciones_extintores;
create policy "e49 inspecciones insert" on public.inspecciones_extintores
for insert to authenticated with check (public.puede_gestionar_proyecto(proyecto_id));

drop policy if exists "e49 inspecciones update" on public.inspecciones_extintores;
create policy "e49 inspecciones update" on public.inspecciones_extintores
for update to authenticated using (public.puede_gestionar_proyecto(proyecto_id)) with check (public.puede_gestionar_proyecto(proyecto_id));

drop policy if exists "e49 inspecciones delete" on public.inspecciones_extintores;
create policy "e49 inspecciones delete" on public.inspecciones_extintores
for delete to authenticated using (public.es_admin_sistema());

drop policy if exists "e49 detalles select" on public.inspeccion_extintor_detalles;
create policy "e49 detalles select" on public.inspeccion_extintor_detalles
for select to authenticated using (
  exists(select 1 from public.inspecciones_extintores i where i.id=inspeccion_id and public.puede_acceder_proyecto(i.proyecto_id))
);

drop policy if exists "e49 detalles insert" on public.inspeccion_extintor_detalles;
create policy "e49 detalles insert" on public.inspeccion_extintor_detalles
for insert to authenticated with check (
  exists(select 1 from public.inspecciones_extintores i where i.id=inspeccion_id and public.puede_gestionar_proyecto(i.proyecto_id))
);

drop policy if exists "e49 detalles update" on public.inspeccion_extintor_detalles;
create policy "e49 detalles update" on public.inspeccion_extintor_detalles
for update to authenticated using (
  exists(select 1 from public.inspecciones_extintores i where i.id=inspeccion_id and public.puede_gestionar_proyecto(i.proyecto_id))
) with check (
  exists(select 1 from public.inspecciones_extintores i where i.id=inspeccion_id and public.puede_gestionar_proyecto(i.proyecto_id))
);

drop policy if exists "e49 detalles delete" on public.inspeccion_extintor_detalles;
create policy "e49 detalles delete" on public.inspeccion_extintor_detalles
for delete to authenticated using (
  exists(select 1 from public.inspecciones_extintores i where i.id=inspeccion_id and public.puede_gestionar_proyecto(i.proyecto_id))
);

-- Storage privado para fotos de extintores.
drop policy if exists "e49 extintores storage insert" on storage.objects;
create policy "e49 extintores storage insert" on storage.objects
for insert to authenticated
with check (
  bucket_id='evidencias-ssomac'
  and split_part(name,'/',1)='inspecciones-extintores'
  and split_part(name,'/',2) ~* '^[0-9a-f-]{36}$'
  and exists(
    select 1 from public.inspecciones_extintores i
    where i.id=case when split_part(name,'/',2) ~* '^[0-9a-f-]{36}$' then split_part(name,'/',2)::uuid else null end
      and public.puede_gestionar_proyecto(i.proyecto_id)
  )
);

drop policy if exists "e49 extintores storage select" on storage.objects;
create policy "e49 extintores storage select" on storage.objects
for select to authenticated
using (
  bucket_id='evidencias-ssomac'
  and split_part(name,'/',1)='inspecciones-extintores'
  and split_part(name,'/',2) ~* '^[0-9a-f-]{36}$'
  and exists(
    select 1 from public.inspecciones_extintores i
    where i.id=case when split_part(name,'/',2) ~* '^[0-9a-f-]{36}$' then split_part(name,'/',2)::uuid else null end
      and public.puede_acceder_proyecto(i.proyecto_id)
  )
);

drop policy if exists "e49 extintores storage update" on storage.objects;
create policy "e49 extintores storage update" on storage.objects
for update to authenticated
using (
  bucket_id='evidencias-ssomac'
  and split_part(name,'/',1)='inspecciones-extintores'
  and split_part(name,'/',2) ~* '^[0-9a-f-]{36}$'
  and exists(
    select 1 from public.inspecciones_extintores i
    where i.id=case when split_part(name,'/',2) ~* '^[0-9a-f-]{36}$' then split_part(name,'/',2)::uuid else null end
      and public.puede_gestionar_proyecto(i.proyecto_id)
  )
)
with check (
  bucket_id='evidencias-ssomac'
  and split_part(name,'/',1)='inspecciones-extintores'
);

commit;

select 'ETAPA 49 OK' as resultado;
